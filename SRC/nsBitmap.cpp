//---------------------------------------------------------------------------
#include<vcl.h>
#pragma hdrstop

#include "nsBitmap.h"
//---------------------------------------------------------------------------
#pragma package(smart_init)

//---------------------------------------------------------------------------
//コンストラクタ
//---------------------------------------------------------------------------
nsBitmap::nsBitmap()
{
	//初期化
	pBmp = nullptr;
	//ビットマップ作成
	pBmp = new TBitmap();
}
//---------------------------------------------------------------------------
//コピーコンストラクタ
//---------------------------------------------------------------------------
nsBitmap::nsBitmap(const nsBitmap& h)
:nsBitmap()
{
	//ビットマップコピー
	pBmp->Assign(h.pBmp);
}
//---------------------------------------------------------------------------
//デストラクタ
//---------------------------------------------------------------------------
nsBitmap::~nsBitmap()
{
	if(pBmp != nullptr)
	{
		delete pBmp;
	}
}
//---------------------------------------------------------------------------
//代入
//---------------------------------------------------------------------------
nsBitmap& nsBitmap::operator = (const nsBitmap& h)
{
	//ビットマップコピー
	pBmp->Assign(h.pBmp);

	return *this;
}
//---------------------------------------------------------------------------
//->演算子
//---------------------------------------------------------------------------
TBitmap* nsBitmap::operator -> ()
{
	return pBmp;
}
//---------------------------------------------------------------------------
//ビットマップ再構築
//---------------------------------------------------------------------------
bool nsBitmap::reset()
{
	//再構築
	delete pBmp;
	pBmp = new TBitmap();

	return true;
}
//---------------------------------------------------------------------------
//ビットマップ取得
//---------------------------------------------------------------------------
TBitmap *nsBitmap::get() const
{
	return pBmp;
}
